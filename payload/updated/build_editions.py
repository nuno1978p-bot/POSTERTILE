"""Build independent Owner and Private Preview Windows binaries. NO private keys in outputs."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys

from license_authority import public_key_path

ROOT = Path(__file__).resolve().parent
WORK = ROOT / "_build_work"
DIST = ROOT / "dist_editions"
RELEASE = ROOT / "release_editions"
BASE_MODULES = [
    "main.py", "license_runtime.py", "license_core.py", "poster_framing.py",
    "composition_drag.py", "postertile_engine.py", "a3_two_a4.py",
    "printer_calibration.py", "version_info.txt",
]
APP_NAMES = {
    "owner": "NONIVERUS PosterTile Owner",
    "preview": "NONIVERUS PosterTile Private Preview",
}
APPIDS = {
    "owner": "A21297EC-47C8-4A17-8CB9-DA95C70645A9",
    "preview": "47FD65E8-338F-45CE-9F74-2DF0B0AB9C41",
}

def execute(args, cwd=None):
    print("\n>>>", " ".join(str(x) for x in args), flush=True)
    subprocess.run([str(x) for x in args], cwd=cwd, check=True)

def prepare_stage(edition):
    stage = WORK / "stage" / edition
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    for name in BASE_MODULES:
        shutil.copy2(ROOT / name, stage / name)
    for name in ("ui", "assets"):
        shutil.copytree(ROOT / name, stage / name)
    (stage / "edition_config.py").write_text(
        "# Generated by NONIVERUS edition builder; bundled inside EXE.\n"
        f"EDITION = {edition!r}\n", encoding="ascii")
    version_path = stage / "version_info.txt"
    version_txt = version_path.read_text(encoding="utf8")
    version_txt = version_txt.replace("OriginalFilename','NONIVERUS PosterTile.exe'",
        f"OriginalFilename','{APP_NAMES[edition]}.exe'")
    version_txt = version_txt.replace("FileDescription','NONIVERUS PosterTile Luxury Studio'",
        f"FileDescription','{APP_NAMES[edition]}'")
    version_path.write_text(version_txt, encoding="utf8")
    return stage

def compile_native():
    key = public_key_path()
    if not key.is_file() or key.stat().st_size != 32:
        raise RuntimeError(
            "Chave pública inexistente. Executa: "
            ".venv\\Scripts\\python.exe license_authority.py init")
    if not shutil.which("cargo"):
        raise RuntimeError("Rust cargo não encontrado. Instala Rust e MSVC Build Tools.")
    native_stage = WORK / "native_source"
    if native_stage.exists():
        shutil.rmtree(native_stage)
    shutil.copytree(ROOT / "native_license", native_stage)
    shutil.copy2(key, native_stage / "public_key.bin")
    target = WORK / "cargo_target"
    execute(["cargo", "build", "--release", "--manifest-path",
             native_stage / "Cargo.toml", "--target-dir", target])
    dll = target / "release" / "nv_license_native.dll"
    if not dll.is_file():
        raise RuntimeError(f"DLL nativa não encontrada: {dll}")
    return dll

UPDATE_INSTALLER_CODE = r"""
[Code]
{ Detecao de atualizacao pela mesma identidade AppId; Owner e Preview independentes. }
var
  NVPreviousVersion: String;
  NVExistingInstall: Boolean;
  NVOriginalNextText: String;

function NVFindPreviousVersion(var InstalledVersion: String): Boolean;
var
  UninstallKey: String;
begin
  UninstallKey := 'Software\Microsoft\Windows\CurrentVersion\Uninstall\{__APPID__}_is1';
  Result := RegQueryStringValue(HKLM64, UninstallKey, 'DisplayVersion', InstalledVersion);
  if not Result then
    Result := RegQueryStringValue(HKCU, UninstallKey, 'DisplayVersion', InstalledVersion);
end;

function InitializeSetup: Boolean;
begin
  NVPreviousVersion := '';
  NVExistingInstall := NVFindPreviousVersion(NVPreviousVersion);
  Result := True;
end;

procedure InitializeWizard;
begin
  NVOriginalNextText := WizardForm.NextButton.Caption;
end;

procedure CurPageChanged(CurPageID: Integer);
begin
  if not NVExistingInstall then
    Exit;

  if CurPageID = wpReady then
  begin
    if ActiveLanguage = 'portuguese' then
    begin
      WizardForm.ReadyLabel.Caption :=
        'Instalacao existente detetada: versao ' + NVPreviousVersion + '.' + #13#10 +
        'O instalador vai atualizar esta edicao para a versao {#MyAppVersion}, ' +
        'mantendo a pasta da aplicacao e a licenca existente.';
      WizardForm.NextButton.Caption := '&Atualizar';
    end
    else
    begin
      WizardForm.ReadyLabel.Caption :=
        'Existing installation detected: version ' + NVPreviousVersion + '.' + #13#10 +
        'Setup will update this edition to version {#MyAppVersion}, ' +
        'keeping the application folder and existing license.';
      WizardForm.NextButton.Caption := '&Update';
    end;
  end
  else if (CurPageID = wpWelcome) or (CurPageID = wpSelectDir) or
          (CurPageID = wpSelectProgramGroup) or (CurPageID = wpSelectTasks) then
    WizardForm.NextButton.Caption := NVOriginalNextText;
end;
"""


def inno_binary():
    candidates = [
        Path(os.environ.get("ProgramFiles(x86)", "")) / "Inno Setup 6" / "ISCC.exe",
        Path(os.environ.get("ProgramFiles", "")) / "Inno Setup 6" / "ISCC.exe",
        Path(r"D:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
    ]
    return next((c for c in candidates if c.is_file()), shutil.which("ISCC.exe"))

def build_authority_executable(python_exe):
    """Portable Owner-only administration GUI. NEVER bundled into Preview."""
    stage = WORK / "stage" / "authority"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    for name in ("license_authority.py", "license_core.py", "version_info.txt"):
        shutil.copy2(ROOT / name, stage / name)
    (stage / "assets").mkdir()
    shutil.copy2(ROOT / "assets" / "branding" / "postertile_icon.ico", stage / "assets" / "authority.ico")
    name = "NONIVERUS License Authority"
    dest = ROOT / "dist_owner_tools"
    execute([
        python_exe, "-m", "PyInstaller", "--noconfirm", "--clean",
        "--onedir", "--windowed", "--name", name,
        "--icon", stage / "assets" / "authority.ico",
        "--distpath", dest,
        "--workpath", WORK / "pyinstaller",
        "--specpath", WORK / "spec",
        "--hidden-import", "PySide6.QtWidgets",
        stage / "license_authority.py",
    ], cwd=stage)
    exe = dest / name / (name + ".exe")
    if not exe.is_file():
        raise RuntimeError("Ferramenta License Authority não gerada: " + str(exe))
    print("FERRAMENTA ADMINISTRATIVA PRIVADA:", exe)


def build_one(edition, python_exe, only_exe=False):
    exe_name=APP_NAMES[edition]
    stage=prepare_stage(edition)
    extra=[]
    if edition == "preview":
        dll=compile_native()
        extra=["--add-binary", f"{dll};native"]
    pyinstaller=[
        python_exe,"-m","PyInstaller","--noconfirm","--clean",
        "--onedir","--windowed","--name",exe_name,
        "--icon",stage / "assets" / "branding" / "postertile_icon.ico",
        "--version-file",stage / "version_info.txt",
        "--distpath",DIST,"--workpath",WORK / "pyinstaller",
        "--specpath",WORK / "spec",
        "--add-data", f"{stage / 'ui'};ui",
        "--add-data", f"{stage / 'assets'};assets",
        "--collect-all","PySide6.QtQml",
        "--hidden-import","PySide6.QtQuick",
        "--hidden-import","PySide6.QtQuickControls2",
        "--hidden-import","PySide6.QtQuickWidgets",
        *extra,
        stage / "main.py"
    ]
    execute(pyinstaller, cwd=stage)
    exe=DIST / exe_name / f"{exe_name}.exe"
    if not exe.is_file():
        raise RuntimeError("Executável não encontrado depois do build: " + str(exe))
    if edition == "preview":
        expected=DIST / exe_name / "_internal" / "native" / "nv_license_native.dll"
        if not expected.is_file():
            raise RuntimeError("Preview SEM DLL de verificação: build recusado. " + str(expected))
    script, filename = make_installer_script(edition, exe_name)
    if not only_exe:
        iscc=inno_binary()
        if not iscc:
            raise RuntimeError("EXE criado, mas Inno Setup 6 ISCC.exe não foi encontrado.")
        RELEASE.mkdir(parents=True, exist_ok=True)
        execute([iscc, script], cwd=ROOT)
        setup=RELEASE / (filename + ".exe")
        if not setup.is_file():
            raise RuntimeError("Instalador não encontrado: " + str(setup))
        print("SETUP:", setup)
    print("EXECUTÁVEL:", exe)

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("edition", choices=["owner","preview","both"])
    ap.add_argument("--only-exe", action="store_true")
    a=ap.parse_args()
    if sys.platform!="win32":
        raise SystemExit("Build EXE/Setup apenas em Windows. Fontes válidas para testes em outras plataformas.")
    if sys.executable.lower().endswith("pythonw.exe"):
        raise SystemExit("Utilizar python.exe da .venv")
    for edition in (["owner","preview"] if a.edition=="both" else [a.edition]):
        build_one(edition, sys.executable, only_exe=a.only_exe)
        if edition == "owner":
            build_authority_executable(sys.executable)
    return 0

if __name__=="__main__":
    raise SystemExit(main())
